// ============================================================================
// AN FOCUS — Analytics Scripts
// Loads Google Analytics (GA4) and Meta Pixel only when their IDs are set in
// NEXT_PUBLIC_GA_ID / NEXT_PUBLIC_META_PIXEL_ID. Without them nothing loads.
// Events are sent from `@/lib/analytics`.
// ============================================================================

import Script from 'next/script';
import { analyticsConfig } from '@/config/site';

export default function Analytics() {
  const { googleAnalyticsId, metaPixelId } = analyticsConfig;

  return (
    <>
      {googleAnalyticsId && (
        <>
          <Script
            src={`https://www.googletagmanager.com/gtag/js?id=${googleAnalyticsId}`}
            strategy="afterInteractive"
          />
          <Script id="ga4-init" strategy="afterInteractive">
            {`window.dataLayer = window.dataLayer || [];
function gtag(){dataLayer.push(arguments);}
gtag('js', new Date());
gtag('config', ${JSON.stringify(googleAnalyticsId)});`}
          </Script>
        </>
      )}

      {metaPixelId && (
        <Script id="meta-pixel-init" strategy="afterInteractive">
          {`!function(f,b,e,v,n,t,s){if(f.fbq)return;n=f.fbq=function(){n.callMethod?
n.callMethod.apply(n,arguments):n.queue.push(arguments)};if(!f._fbq)f._fbq=n;
n.push=n;n.loaded=!0;n.version='2.0';n.queue=[];t=b.createElement(e);t.async=!0;
t.src=v;s=b.getElementsByTagName(e)[0];s.parentNode.insertBefore(t,s)}(window,
document,'script','https://connect.facebook.net/en_US/fbevents.js');
fbq('init', ${JSON.stringify(metaPixelId)});
fbq('track', 'PageView');`}
        </Script>
      )}
    </>
  );
}
